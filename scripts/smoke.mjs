import { chromium } from "playwright-core";
import assert from "node:assert/strict";

const browser = await chromium.launch({ executablePath: "/Applications/Google Chrome.app/Contents/MacOS/Google Chrome", headless: true });
const baseUrl = process.env.CREDITS_BASE_URL ?? "http://localhost:3000";
const page = await browser.newPage({ viewport: { width: 390, height: 844 } });
page.setDefaultTimeout(10000);
const errors = [];
page.on("pageerror", (error) => errors.push(error.message));
page.on("console", (message) => { if (message.type() === "error") errors.push(message.text()); });

await page.goto(baseUrl, { waitUntil: "domcontentloaded" });
await page.getByPlaceholder("e.g. Alex").waitFor();
assert.equal(await page.getByText("Loading Credits…").count(), 0, "startup must never remain on a loading placeholder");
assert.equal(await page.getByPlaceholder("e.g. Alex").count(), 1, "fresh storage should show onboarding");
await page.locator('[data-setup-ready="true"]').waitFor();
await page.getByPlaceholder("e.g. Alex").fill("Demo");
await page.getByRole("button", { name: "Female" }).click();
await page.getByRole("button", { name: "Get Started" }).click();
await page.getByText("Body Metrics", { exact: true }).waitFor();
await page.getByLabel("Age (years)").fill("30");
await page.getByLabel("Weight (kg)").fill("78");
await page.getByLabel("Height (cm)").fill("178");
await page.getByRole("button", { name: "Next", exact: true }).click();
await page.getByText("Activity Level", { exact: true }).waitFor();
await page.getByRole("button", { name: /Moderate/ }).click();
await page.getByRole("button", { name: "Next", exact: true }).click();
await page.getByText("Your Goal", { exact: true }).waitFor();
await page.getByRole("button", { name: /Maintain/ }).click();
await page.getByRole("button", { name: /Start Tracking/ }).click();
await page.getByText("Hey, Demo").waitFor();
await page.reload({ waitUntil: "domcontentloaded" });
await page.getByText("Hey, Demo").waitFor();
assert.equal(await page.getByText("Breakfast", { exact: true }).count(), 1);
await page.getByRole("button", { name: "More" }).click();
page.once("dialog", (dialog) => dialog.accept());
await page.getByText("Load interactive demo data").click();
await page.getByText("Demo data loaded").waitFor();
await page.getByRole("button", { name: "Calendar" }).click();
await page.getByText("MONTH SUMMARY").waitFor();
assert.ok(await page.locator(".calendar-grid button.logged").count() >= 7, "calendar should mark logged demo days in the current month");
await page.locator(".calendar-grid button.logged").last().click();
await page.getByText("Nutrition detail").waitFor();
await page.locator("nav.tracker-nav").getByRole("button", { name: "Today" }).evaluate((button) => button.click());
await page.waitForTimeout(300);
assert.ok(await page.locator("article.food-row").count() >= 4, "demo diary should render meal entries");
await page.getByRole("button", { name: "Progress" }).evaluate((button) => button.click());
await page.getByText("7-day weight trend").waitFor();
await page.locator("nav.tracker-nav").getByRole("button", { name: "Add" }).evaluate((button) => button.click());
await page.getByPlaceholder("Search food or brand").fill("Chicken");
assert.ok(await page.getByText("Chicken Breast (100g)").count() >= 1, "local food search should filter presets");
await page.getByRole("button", { name: "Barcode" }).click();
await page.getByPlaceholder("e.g. 3017624010701").fill("3017624010701");
await page.getByRole("button", { name: "Look up" }).click();
await page.getByText("Nutella", { exact: true }).waitFor({ timeout: 15000 });
await page.getByRole("button", { name: "Save Nutella on device" }).click();
await page.getByRole("button", { name: "Foods" }).click();
await page.getByPlaceholder("Search food or brand").fill("Nutella");
await page.getByText("Nutella", { exact: true }).click();
await page.getByLabel("Quantity").fill("0.25");
await page.getByRole("button", { name: "Save to diary" }).click();
await page.getByText("Added to diary").waitFor();
await page.locator("nav.tracker-nav").getByRole("button", { name: "Today" }).evaluate((button) => button.click());
await page.getByText("Nutella", { exact: true }).waitFor();
await page.getByText("Nutella", { exact: true }).click();
await page.getByLabel("Notes").fill("Quarter serving test");
await page.getByRole("button", { name: "Save to diary" }).click();

await page.getByRole("button", { name: "Progress" }).evaluate((button) => button.click());
await page.getByRole("button", { name: "Check in" }).click();
await page.getByLabel("Weight (kg)").fill("77.4");
await page.getByLabel("Body fat %").fill("18.5");
await page.getByRole("button", { name: "Save check-in" }).click();
await page.getByText("77.4").waitFor();
await page.getByRole("heading", { name: "Body measurements" }).locator("xpath=../..").getByRole("button", { name: "Add" }).click();
await page.getByRole("dialog", { name: "Body measurements" }).waitFor();
await page.getByLabel("chest (cm)").fill("101.5");
await page.getByLabel("hips (cm)").fill("96");
await page.getByRole("button", { name: "Save measurements" }).click();
await page.getByText("101.5 cm").waitFor();

await page.getByRole("button", { name: "Edit profile" }).click();
await page.getByLabel("Name").fill("Demo Updated");
await page.getByRole("button", { name: "Save profile" }).click();
await page.locator("nav.tracker-nav").getByRole("button", { name: "Today" }).evaluate((button) => button.click());
await page.getByText("Hey, Demo Updated").waitFor();

await page.locator("nav.tracker-nav").getByRole("button", { name: "Add" }).evaluate((button) => button.click());
await page.getByRole("button", { name: "Bowl" }).click();
await page.getByRole("button", { name: "Build a bowl" }).click();
await page.getByLabel("Bowl name").fill("Smoke test bowl");
await page.getByRole("button", { name: /Banana/ }).click();
await page.getByRole("button", { name: /Chicken Breast/ }).click();
await page.getByLabel("Banana quantity").fill("1.5");
await page.getByRole("button", { name: "Save bowl" }).click();
await page.getByText("Smoke test bowl").waitFor();
await page.getByText("View 2 ingredients and macros").click();
await page.getByText(/Banana/).last().waitFor();
await page.getByRole("heading", { name: "🥣 Smoke test bowl" }).locator("xpath=../..").getByRole("button", { name: "Log bowl" }).click();
await page.getByRole("button", { name: "Save to diary" }).click();
await page.getByText("Added to diary").waitFor();
assert.deepEqual(errors.filter((message) => !message.includes("favicon")), [], `browser errors: ${errors.join("\n")}`);
await page.screenshot({ path: "demo-smoke.png", fullPage: true });
await browser.close();
console.log("Browser smoke test passed: onboarding, hydration, diary, profile, measurements, progress, search, barcode and recipes.");
